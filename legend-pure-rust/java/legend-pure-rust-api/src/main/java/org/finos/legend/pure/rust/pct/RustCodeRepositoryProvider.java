package org.finos.legend.pure.rust.pct;

import org.finos.legend.pure.m3.serialization.filesystem.repository.CodeRepository;
import org.finos.legend.pure.m3.serialization.filesystem.repository.CodeRepositoryProvider;
import org.finos.legend.pure.m3.serialization.filesystem.repository.GenericCodeRepository;

/**
 * The repository {@code platform_rust}, shared by every transport: the {@code Rust_Native} PCT adapter, the
 * corpus on the Rust evaluator alone.
 */
public class RustCodeRepositoryProvider implements CodeRepositoryProvider
{
    @Override
    public CodeRepository repository()
    {
        return GenericCodeRepository.build("platform_rust.definition.json");
    }
}
