package org.finos.legend.pure.rust.jni.pct;

import junit.framework.Test;
import org.eclipse.collections.api.list.MutableList;
import org.finos.legend.pure.m3.PlatformCodeRepositoryProvider;
import org.finos.legend.pure.m3.pct.reports.config.PCTReportConfiguration;
import org.finos.legend.pure.m3.pct.reports.config.exclusion.ExclusionSpecification;
import org.finos.legend.pure.m3.pct.reports.model.Adapter;
import org.finos.legend.pure.m3.pct.shared.model.ReportScope;
import org.finos.legend.pure.rust.pct.PctSuites;

/**
 * The essential PCT corpus through the interpreted engine with the
 * {@code Rust_JNI} adapter: every test lambda runs in the Rust evaluator.
 * The manifest is generated by {@link RebaseRustJniManifests}.
 */
public class Test_RustJni_EssentialFunctions_PCT extends PCTReportConfiguration
{
    private static final ReportScope reportScope = PlatformCodeRepositoryProvider.essentialFunctions;
    private static final Adapter adapter = PlatformCodeRepositoryProvider.rustJniAdapter;
    private static final String platform = "interpreted";
    private static final String manifestPath = "platform/pure/essential/pct_essential_interpreted_rust_jni.json";

    public static Test suite()
    {
        return PctSuites.interpreted(adapter, reportScope, manifestPath);
    }

    @Override
    public ReportScope getReportScope()
    {
        return reportScope;
    }

    @Override
    public MutableList<ExclusionSpecification> expectedFailures()
    {
        return buildExpectedFailures(manifestPath);
    }

    @Override
    public Adapter getAdapter()
    {
        return adapter;
    }

    @Override
    public String getPlatform()
    {
        return platform;
    }
}
